import type { TenseId } from '@/types/verb'

/**
 * Per-verb material for the short example shown next to every conjugated form.
 *
 * [Italian complement, English complement, English verb, options]
 *  - Complements are time-neutral so they fit every tense and person.
 *    "sg|pl" alternatives are used when a word must agree in number (famoso|famosi).
 *  - English verb: "base|past|participle|-ing" — missing parts are derived regularly.
 *    Words after the first are a particle: "get up|got|got|getting" → "I got up".
 *    "be" is handled specially (am/is/are, was/were, been).
 */
export interface PhraseOptions {
  /** State verb: imperfetto → English simple past ("I knew"), no progressive example. */
  stative?: boolean
  /** Tenses for which no natural example exists (e.g. an imperative of nascere). */
  skip?: TenseId[]
  /** English participle when the verb is a "be + …" phrase (nascere → born). */
  ppEn?: string
  /** English subject with an object pronoun instead (piacere: "Maria likes me"). */
  invert?: string
  /** Only third-person examples, with these subjects [it, en] (succedere). */
  third?: { sg: [string, string]; pl: [string, string] }
}

